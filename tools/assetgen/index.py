#!/usr/bin/env python3
"""Write game/src/data/assetIndex.ts from the processed files in game/public/assets.

Run after process.py:  python3 -I tools/assetgen/index.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
A = ROOT / "game/public/assets"
OUT = ROOT / "game/src/data/assetIndex.ts"


def stems(d):
    return sorted(p.stem for p in (A / d).glob("*.png"))


def main():
    sheets = {}
    for j in sorted((A / "sprites").glob("*.json")):
        m = json.loads(j.read_text())
        sheets[j.stem] = [m["frameWidth"], m["frameHeight"], m["frames"]]
    lines = [
        "// AUTO-GENERATED by tools/assetgen/index.py — do not edit by hand.",
        "",
        "/** key -> [frameWidth, frameHeight, frameCount] */",
        f"export const SHEETS: Record<string, [number, number, number]> = {json.dumps(sheets)};",
        f"export const TILES = {json.dumps(stems('tiles'))} as const;",
        f"export const PROPS = {json.dumps(stems('props'))} as const;",
        f"export const PORTRAITS = {json.dumps(stems('portraits'))} as const;",
        f"export const CGS = {json.dumps(stems('cg'))} as const;",
        "",
    ]
    OUT.write_text("\n".join(lines))
    print("wrote", OUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
